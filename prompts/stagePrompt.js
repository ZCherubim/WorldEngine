export function fillTask(names) {
    const list = (names || []).join('、');
    return `【补全任务】下面这些角色在上一轮里漏掉了，本轮**必须**为每一个输出一行：

${list}

要求：
- 每人一行：时间 地点 做什么 / 心情 / 目标
- 交互角色写细一点；冷却 / 未出场角色一句话概括就够
- 保持她们原有的类别和挂载点（"父 > 子"），名字用状态清单里的原名，不要发明新写法
- **不要改动任何一个角色的性格字段**（性格 / 底色 / 软肋 / 说话 / 行为）
- 只输出这些角色，不要输出其他内容`;
}

